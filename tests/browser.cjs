/* Run: PLAYWRIGHT_MODULE=/path/to/playwright node tests/browser.cjs */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const output = process.env.SCREENSHOT_DIR || '/tmp/zae-screenshots';
fs.mkdirSync(output, {recursive:true});
const base = process.env.TEST_URL || 'http://127.0.0.1:8765';
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || undefined, args:['--no-sandbox']});
  try {
  const errors = [];
  async function page(options = {}, saveData = true, mock = true) {
    const context = await browser.newContext(options);
    await context.addInitScript(({saveData}) => {
      Object.defineProperty(navigator, 'connection', {value:{saveData}, configurable:true});
      window.testCLS = 0; window.testLoaded = false; addEventListener('load', () => {window.testLoaded = true;});
      new PerformanceObserver(list => {for (const entry of list.getEntries()) if (!entry.hadRecentInput) window.testCLS += entry.value;}).observe({type:'layout-shift', buffered:true});
    }, {saveData});
    const p = await context.newPage();
    p.on('pageerror', error => errors.push(error.message));
    p.on('console', msg => {if (msg.type() === 'error') errors.push(msg.text());});
    if (mock) await p.route('https://www.youtube-nocookie.com/embed/**', async route => {
      assert.equal(await p.evaluate(() => window.testLoaded), true, 'YouTube request only after load');
      return route.fulfill({contentType:'text/html', body:`<!doctype html><html><body style="margin:0;background:#10131a;color:white;font:20px sans-serif;display:grid;place-items:center;height:100vh">YouTube player fixture<script>
      window.played=false; let ready=false; setTimeout(()=>{ready=true;parent.postMessage(JSON.stringify({event:'onReady'}),'*'); if(new URL(location.href).searchParams.get('autoplay')==='1') {window.played=true; parent.postMessage(JSON.stringify({event:'infoDelivery',info:{playerState:1}}),'*');}},700);
      addEventListener('message', e=>{let d;try{d=JSON.parse(e.data)}catch{return}if(ready&&d.func==='playVideo'){window.played=true;parent.postMessage(JSON.stringify({event:'infoDelivery',info:{playerState:1}}),'*');}});
      </script></body></html>`});});
    return p;
  }
  const beforeLoad = await page({}, false);
  let releaseImage;
  const imageGate = new Promise(resolve => {releaseImage = resolve;});
  await beforeLoad.route('**/assets/thumbs/ILF5shEX-fg.avif', async route => {await imageGate; await route.continue();});
  await beforeLoad.goto(base, {waitUntil:'domcontentloaded'});
  assert.equal(await beforeLoad.evaluate(() => window.testLoaded), false);
  await beforeLoad.locator('.zl-shim').click();
  assert.equal(await beforeLoad.locator('iframe').count(), 0, 'early gesture waits for window load');
  assert.match(await beforeLoad.locator('.player-status').textContent(), /Loading/);
  releaseImage();
  await beforeLoad.waitForFunction(() => document.querySelector('.zl-player').classList.contains('ready'));
  assert.match(await beforeLoad.locator('iframe').getAttribute('src'), /autoplay=1/);
  assert.equal(await beforeLoad.locator('iframe').count(), 1);
  await beforeLoad.context().close();
  const desktop = await page({viewport:{width:1366,height:800}});
  await desktop.goto(base, {waitUntil:'load'});
  await desktop.locator('.zl').scrollIntoViewIfNeeded();
  await desktop.waitForTimeout(500);
  assert.equal(await desktop.locator('.zl iframe').count(), 0, 'Save-Data skips preload');
  await desktop.screenshot({path:`${output}/desktop.png`, fullPage:true});
  await desktop.evaluate(() => scrollTo(0,0)); await desktop.waitForTimeout(400);
  await desktop.screenshot({path:`${output}/desktop-hero.png`});
  const disclosure = desktop.locator('.disclosure');
  await disclosure.click(); await desktop.waitForTimeout(400);
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'true');
  assert.equal(await desktop.locator('.snippet').getAttribute('aria-hidden'), 'false');
  await desktop.screenshot({path:`${output}/desktop-expanded.png`, fullPage:true});
  await disclosure.click(); await desktop.waitForTimeout(400);
  assert.equal(await disclosure.getAttribute('aria-expanded'), 'false');
  await desktop.locator('.zl-shim').click();
  assert.match(await desktop.locator('.zl iframe').getAttribute('src'), /autoplay=1/);
  await desktop.waitForFunction(() => document.querySelector('.zl-player').classList.contains('ready'));
  assert.equal(await desktop.locator('.zl iframe').count(), 1);
  await desktop.waitForTimeout(400);
  assert.equal(await desktop.locator('.zl iframe').evaluate(el => getComputedStyle(el).opacity), '1');
  await desktop.context().close();
  const mobile = await page({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
  await mobile.goto(base); await mobile.locator('.zl').scrollIntoViewIfNeeded(); await mobile.waitForTimeout(400);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no horizontal overflow');
  await mobile.screenshot({path:`${output}/mobile.png`, fullPage:true});
  await mobile.locator('.zl').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 90)); await mobile.waitForTimeout(500);
  assert.equal(await mobile.locator('.sticky-cta').isVisible(), false, 'booking bar clears hero controls');
  await mobile.screenshot({path:`${output}/mobile-hero.png`});
  await mobile.locator('.disclosure').focus(); await mobile.keyboard.press('Enter');
  assert.equal(await mobile.locator('.disclosure').getAttribute('aria-expanded'), 'true');
  await mobile.keyboard.press('Space');
  assert.equal(await mobile.locator('.disclosure').getAttribute('aria-expanded'), 'false');
  assert.equal(await mobile.locator('.subscribe').getAttribute('href'), 'https://www.youtube.com/@ZachAdamsEffect?sub_confirmation=1');
  await mobile.context().close();
  const preload = await page({viewport:{width:1366,height:800}}, false);
  await preload.goto(base); await preload.waitForFunction(() => document.querySelector('.zl-player').classList.contains('ready'));
  assert.match(await preload.locator('.zl iframe').getAttribute('src'), /autoplay=0/);
  await preload.waitForTimeout(500);
  assert.equal(await preload.locator('.zl iframe').evaluate(el => getComputedStyle(el).opacity), '1');
  const cls = await preload.evaluate(() => window.testCLS);
  assert.ok(cls < .02, `CLS ${cls}`);
  await preload.context().close();
  const pending = await page({}, false);
  await pending.goto(base);
  await pending.waitForSelector('.zl iframe', {state:'attached'});
  assert.equal(await pending.locator('.zl-player').evaluate(el => el.classList.contains('ready')), false, 'click while preload is pending');
  await pending.locator('.zl-shim').click({force:true});
  await pending.waitForFunction(() => document.querySelector('.zl-player').classList.contains('ready'));
  await pending.waitForTimeout(900);
  assert.equal(await pending.locator('iframe').count(), 1);
  assert.equal(await pending.locator('.player-status').textContent(), '');
  assert.equal(await pending.frameLocator('iframe').locator('body').evaluate(() => window.played), true, 'pending gesture actually commands playback');
  await pending.context().close();
  const feed = await page({viewport:{width:1200,height:900}}, false);
  await feed.goto(`${base}/episodes/`);
  await feed.locator('#episode-feed').evaluate(el => el.scrollIntoView({block:'end'}));
  await feed.waitForFunction(() => document.querySelector('#episode-feed').children.length === 6);
  assert.equal(await feed.locator('iframe').count(), 0);
  await feed.screenshot({path:`${output}/archive.png`, fullPage:true});
  await feed.context().close();
  const reduced = await page({reducedMotion:'reduce'});
  await reduced.goto(base);
  assert.equal(await reduced.locator('.zl-shim').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  assert.equal(await reduced.locator('.snippet').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await reduced.context().close();
  const fetchFailure = await page();
  await fetchFailure.route('**/episodes/feed/2.json', route => route.fulfill({contentType:'application/json',body:'Unavailable'}));
  await fetchFailure.goto(`${base}/episodes/`);
  await fetchFailure.locator('.load-more').click();
  await fetchFailure.waitForFunction(() => document.querySelector('.load-more').dataset.failed === 'true');
  await fetchFailure.locator('.load-more').click();
  assert.match(fetchFailure.url(), /episodes\/page\/2\//);
  await fetchFailure.context().close();
  const fallback = await page();
  await fallback.addInitScript(() => {delete window.IntersectionObserver;});
  await fallback.goto(`${base}/episodes/`);
  assert.equal(await fallback.locator('.ep-slide').count(), 3);
  await fallback.locator('.load-more').click();
  await fallback.waitForFunction(() => document.querySelector('#episode-feed').children.length === 6);
  assert.equal(await fallback.evaluate(() => document.activeElement.closest('.ep-slide') === document.querySelectorAll('.ep-slide')[3]), true);
  await fallback.context().close();
  const nojs = await browser.newPage({javaScriptEnabled:false});
  await nojs.goto(base);
  assert.match(await nojs.locator('.zl-shim').getAttribute('href'), /youtube.com\/watch/);
  await nojs.goto(`${base}/episodes/`); await nojs.locator('.load-more').click();
  assert.match(nojs.url(), /episodes\/page\/2\//);
  await nojs.context().close();
  const blocked = await page();
  await blocked.unroute('https://www.youtube-nocookie.com/embed/**');
  await blocked.route('https://www.youtube-nocookie.com/embed/**', route => route.fulfill({contentType:'text/html',body:'Blocked'}));
  await blocked.goto(base); await blocked.locator('.zl-shim').click();
  await blocked.waitForFunction(() => document.querySelector('.player-status').textContent.includes('could not start'), null, {timeout:10000});
  assert.equal(await blocked.locator('.zl-shim').getAttribute('target'), '_blank');
  assert.equal(await blocked.locator('iframe').count(), 0);
  await blocked.context().close();
  const local = await page();
  await local.route('**/fallback.mp4', () => {}); // Hold media response while checking native fallback state.
  await local.unroute('https://www.youtube-nocookie.com/embed/**');
  await local.route('https://www.youtube-nocookie.com/embed/**', route => route.fulfill({contentType:'text/html', body:`<script>setTimeout(()=>parent.postMessage(JSON.stringify({event:'onError'}),'*'),200)</script>`}));
  await local.goto(base);
  await local.locator('.zl-player').evaluate(el => {el.dataset.mp4 = '/fallback.mp4';});
  await local.locator('.zl-shim').click();
  await local.waitForSelector('.zl-player video');
  assert.equal(await local.locator('video').evaluate(el => el.controls && el.autoplay), true);
  await local.locator('video').evaluate(el => el.dispatchEvent(new Event('error')));
  assert.equal(await local.locator('.zl-shim').getAttribute('target'), '_blank');
  assert.match(await local.locator('.zl-play').textContent(), /Open YouTube/);
  await local.context().close();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({result:'PASS', tests:['Save-Data','early-click autoplay=1','single iframe','background readiness/crossfade','disclosure','infinite scroll','no observer load more/focus','no JS pagination','blocked timeout/new-tab fallback','optional native video and media-error fallback','no overflow','no console errors'], CLS:cls, screenshots:output},null,2));
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exit(1);});
